#!/bin/sh
# ============================================================================
# Publish the module's MIME defaults to ~/.config/mimeapps.list.
#
# xdg-open reads that one file for [Default Applications]; anything not listed
# there falls back to whatever the last installed .desktop claimed (this is how
# gimp ended up owning application/pdf). The module keeps a managed list at
# _config/mime/apps.list, installed to ~/.config/mime/apps.list; this script
# merges it over the current file, so manual `xdg-mime set` choices for MIME
# types the module does not cover survive.
#
# Run by xdg-mime-sync.service on sway session start and after every reload
# (start-session-services.sh, itself exec_always in appearance.conf).
# ============================================================================
set -u

src="${XDG_CONFIG_HOME:-$HOME/.config}/mime/apps.list"
dest="${XDG_CONFIG_HOME:-$HOME/.config}/mimeapps.list"

[ -f "$src" ] || { echo "xdg-mime-sync: missing $src" >&2; exit 1; }

if [ ! -f "$dest" ]; then
    cp "$src" "$dest"
    exit 0
fi

workdir="$(mktemp -d "${TMPDIR:-/tmp}/xdg-mime-sync.XXXXXX")" || exit 1
trap 'rm -rf "$workdir"' EXIT

# Parse each file into records of section, key and value on three consecutive
# lines. A pure-shell loop, not awk/sed/python: none of them is guaranteed on
# a minimal system, and this must run before any desktop tooling is trusted.
records() {
    section=""
    while IFS= read -r line || [ -n "$line" ]; do
        line="${line%$'\r'}"
        case "$line" in
            ''|'#'*) continue ;;
            '['*']') section="${line#[}"; section="${section%]}" ;;
            *'='*)
                [ -n "$section" ] || continue
                printf '%s\n%s\n%s\n' "$section" "${line%%=*}" "${line#*=}" ;;
        esac
    done
}

records < "$src" > "$workdir/mods"
records < "$dest" > "$workdir/cur"

emit_defaults() {
    # Section, key and value on three consecutive lines from stdin; writes
    # "key=value" for records whose section matches $1.
    section="$1"
    while IFS= read -r s && IFS= read -r k && IFS= read -r v; do
        [ "$s" = "$section" ] && printf '%s=%s\n' "$k" "$v"
    done
}

merge_associations() {
    # All Added Associations records from both streams on stdin, in order
    # (module first); merges values per key, dedupes, prints merged lines.
    want_key="" vals=""
    flush() {
        [ -n "$want_key" ] || return 0
        merged=""
        oldIFS="$IFS"; IFS=";"
        for entry in $vals; do
            IFS="$oldIFS"
            if [ -n "$entry" ]; then
                case ";$merged" in
                    *";$entry;"*) ;;
                    *) merged="$merged;$entry" ;;
                esac
            fi
            IFS=";"
        done
        IFS="$oldIFS"
        printf '%s=%s;\n' "$want_key" "${merged#;}"
    }
    # Keys already emitted, so the second stream knows when to switch keys.
    while IFS= read -r s && IFS= read -r k && IFS= read -r v; do
        [ "$s" = "Added Associations" ] || continue
        if [ "$k" != "$want_key" ]; then
            if [ -n "$want_key" ] && grep -qxF "$k" "$workdir/seen"; then
                continue  # mods already covered this key
            fi
            flush
            want_key="$k" vals=""
            printf '%s\n' "$k" >> "$workdir/seen"
        fi
        vals="$vals;$v"
    done
    flush
}

tmp="$dest.tmp.$$"
{
    echo "# generated by xdg-mime-sync.sh from ~/.config/mime/apps.list"
    echo "[Default Applications]"
    emit_defaults "Default Applications" < "$workdir/mods"
    # Keys the module already set; user defaults for anything else survive.
    emit_defaults "Default Applications" < "$workdir/mods" | sed 's/=.*//' > "$workdir/modkeys"
    {
        want="Default Applications" keys="$workdir/modkeys"
        while IFS= read -r s && IFS= read -r k && IFS= read -r v; do
            [ "$s" = "$want" ] || continue
            grep -qxF "$k" "$keys" && continue
            printf '%s=%s\n' "$k" "$v"
        done < "$workdir/cur"
    }

    # Added Associations: module handler first in the open-with menu.
    : > "$workdir/seen"
    assoc="$( { cat "$workdir/mods"; cat "$workdir/cur"; } | merge_associations )"
    if [ -n "$assoc" ]; then
        echo ""
        echo "[Added Associations]"
        printf '%s\n' "$assoc"
    fi
} > "$tmp" && mv "$tmp" "$dest"
